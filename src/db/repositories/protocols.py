from collections.abc import Sequence
from datetime import date, datetime
from typing import Protocol

from src.db.models import Event, IdempotencyKey, Outbox, Place, SyncMeta, Ticket


class PlaceRepositoryProtocol(Protocol):
    async def upsert(self, place: Place) -> Place: ...
    async def get(self, place_id: str) -> Place | None: ...


class EventRepositoryProtocol(Protocol):
    async def get(self, event_id: str) -> Event | None: ...

    async def list(
        self,
        *,
        date_from: date | None = None,
        offset: int = 0,
        limit: int = 20,
    ) -> tuple[Sequence[Event], int]: ...

    async def upsert(self, event: Event) -> Event: ...


class TicketRepositoryProtocol(Protocol):
    async def create(self, ticket: Ticket) -> Ticket: ...
    async def get_by_id(self, ticket_id: str) -> Ticket | None: ...
    async def get_by_external_id(self, external_id: str) -> Ticket | None: ...
    async def update_status(self, ticket_id: str, status: str) -> None: ...


class SyncMetaRepositoryProtocol(Protocol):
    async def get(self) -> SyncMeta | None: ...
    async def upsert(self, meta: SyncMeta) -> SyncMeta: ...


class OutboxRepositoryProtocol(Protocol):
    async def create(self, *, event_type: str, payload: dict) -> Outbox: ...
    async def fetch_pending(self, limit: int = 50) -> Sequence[Outbox]: ...
    async def mark_sent(self, outbox_id: str) -> None: ...
    async def mark_failed(
        self,
        outbox_id: str,
        error: str,
        max_attempts: int,
    ) -> None: ...


class IdempotencyRepositoryProtocol(Protocol):
    async def get(self, key: str) -> IdempotencyKey | None: ...
    async def create(
        self, key: str, ticket_id: str, request_hash: str, expires_at: datetime
    ) -> IdempotencyKey: ...
    async def delete(self, key: str) -> None: ...
